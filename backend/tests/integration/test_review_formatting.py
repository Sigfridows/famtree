"""Limited inline formatting remains data across real database/API round trips.

No HTML is generated by the server: the public renderer allowlists three React
inline elements, never interprets URLs/HTML, and escapes all other input.
"""

import pytest

from tests.integration.test_workflows import PREFIX, Workflow, login, register
from tests.integration.test_workflows import workflow as workflow

pytestmark = pytest.mark.integration


async def test_review_formatting_create_read_update_round_trip(workflow: Workflow) -> None:
    async with workflow.client() as author, workflow.client() as guest:
        await register(author, "formatwriter")
        await login(author, "formatwriter")
        center = workflow.ids[0]
        comment = "Una **excelente** atención, *amable* y __constante__."
        response = await author.post(
            PREFIX + f"/asylums/{center}/reviews", json={"rating": 5, "comment": comment}
        )
        assert response.status_code == 201, response.text
        review_id = response.json()["reviewId"]
        assert response.json()["comment"] == comment
        persisted = (await guest.get(PREFIX + f"/asylums/{center}/reviews")).json()
        assert (
            next(item for item in persisted if item["reviewId"] == review_id)["comment"] == comment
        )

        edited = "Atención __constante__ **siempre** <script>alert(1)</script>"
        response = await author.patch(PREFIX + f"/reviews/{review_id}", json={"comment": edited})
        assert response.status_code == 200, response.text
        persisted = (await guest.get(PREFIX + f"/asylums/{center}/reviews")).json()
        assert (
            next(item for item in persisted if item["reviewId"] == review_id)["comment"] == edited
        )
        # The existing contract still bounds serialized formatting; no schema expansion.
        response = await author.patch(
            PREFIX + f"/reviews/{review_id}", json={"comment": "**" + "x" * 500 + "**"}
        )
        assert response.status_code == 422
        assert (await guest.get(PREFIX + "/notifications")).status_code == 401
